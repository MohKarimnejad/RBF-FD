function write_tables(R, outdir)
%WRITE_TABLES  LaTeX tables (booktabs), one pair per polynomial degree d:
%   <outdir>/<problem>_deg<d>.tex     : rows = node levels (h, N_int); for every method
%                                       two columns: max error and sigma (as Tables 4 and 6
%                                       of Davydov & Safarpoor, 2021, side by side)
%   <outdir>/<problem>_rms_deg<d>.tex : rows = node levels; one rms column per method
%  The last row gives the estimated convergence order of the error (slope of the
%  least-squares line fitted to (ln h_m, ln e_m), as in the paper); no order for sigma.
nM = numel(R.methods);
for id = 1:numel(R.degs)
    d = R.degs(id);

    %% max error and sigma
    fid = fopen(fullfile(outdir, sprintf('%s_deg%d.tex', R.problem, d)), 'w');
    fprintf(fid, '%% %s, polynomial degree %d: max error and sigma (generated by write_tables.m)\n', R.problem, d);
    fprintf(fid, '\\begin{tabular}{ll%s}\n\\toprule\n', repmat('cc', 1, nM));
    fprintf(fid, ' & ');
    for iM = 1:nM, fprintf(fid, ' & \\multicolumn{2}{c}{%s}', R.methods{iM}); end
    fprintf(fid, ' \\\\\n');
    for iM = 1:nM, fprintf(fid, '\\cmidrule(lr){%d-%d}', 2*iM+1, 2*iM+2); end
    fprintf(fid, '\n$h$ & $N_{int}$');
    for iM = 1:nM, fprintf(fid, ' & max & $\\sigma$'); end
    fprintf(fid, ' \\\\\n\\midrule\n');
    for im = 1:numel(R.mlist)
        fprintf(fid, '%.3g & %d', R.h(id,im), R.Nint(id,im));
        for iM = 1:nM
            fprintf(fid, ' & %s & %s', fmt(R.max(id,im,iM)), fmt(R.sigma(id,im,iM)));
        end
        fprintf(fid, ' \\\\\n');
    end
    fprintf(fid, '\\midrule\nconv. & order');
    for iM = 1:nM
        fprintf(fid, ' & %s & ', fmto(conv_order(R.h(id,:), R.max(id,:,iM))));
    end
    fprintf(fid, ' \\\\\n\\bottomrule\n\\end{tabular}\n');
    fclose(fid);

    %% rms error
    fid = fopen(fullfile(outdir, sprintf('%s_rms_deg%d.tex', R.problem, d)), 'w');
    fprintf(fid, '%% %s, polynomial degree %d: rms error (generated by write_tables.m)\n', R.problem, d);
    fprintf(fid, '\\begin{tabular}{ll%s}\n\\toprule\n', repmat('c', 1, nM));
    fprintf(fid, '$h$ & $N_{int}$');
    fprintf(fid, ' & %s', R.methods{:});
    fprintf(fid, ' \\\\\n\\midrule\n');
    for im = 1:numel(R.mlist)
        fprintf(fid, '%.3g & %d', R.h(id,im), R.Nint(id,im));
        for iM = 1:nM, fprintf(fid, ' & %s', fmt(R.rms(id,im,iM))); end
        fprintf(fid, ' \\\\\n');
    end
    fprintf(fid, '\\midrule\nconv. & order');
    for iM = 1:nM, fprintf(fid, ' & %s', fmto(conv_order(R.h(id,:), R.rms(id,:,iM)))); end
    fprintf(fid, ' \\\\\n\\bottomrule\n\\end{tabular}\n');
    fclose(fid);
end
end

function a = conv_order(h, e)
% Slope of the least-squares line fitted to (ln h_m, ln e_m), levels with finite error.
ok = isfinite(e) & isfinite(h) & e > 0;
if nnz(ok) < 2, a = NaN; return, end
c = polyfit(log(h(ok)), log(e(ok)), 1);  a = c(1);
end

function s = fmt(v)
% Number in the style of the paper's tables (e.g. 1.2e-05); NaN -> --
if isnan(v), s = '--'; else, s = sprintf('%.1e', v); end
end

function s = fmto(a)
if isnan(a), s = '--'; else, s = sprintf('%.1f', a); end
end
