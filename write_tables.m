function write_tables(R, outdir)
%WRITE_TABLES  LaTeX tables (booktabs) in the style of Davydov & Safarpoor (2021), Table 4:
%  one table per quantity q (rms, max, sigma) and polynomial degree d, file
%  <outdir>/<problem>_<q>_deg<d>.tex. Rows = node levels (h, N_int), columns = methods;
%  for rms and max the last row is the estimated convergence order (slope of the
%  least-squares line fitted to (ln h_m, ln e_m), as in the paper).
qs    = {'rms', 'max', 'sigma'};
qname = {'Root mean square error', 'Maximum error', 'Stability constant $\sigma$'};
nM = numel(R.methods);
for iq = 1:numel(qs)
    D = R.(qs{iq});
    for id = 1:numel(R.degs)
        fname = fullfile(outdir, sprintf('%s_%s_deg%d.tex', R.problem, qs{iq}, R.degs(id)));
        fid = fopen(fname, 'w');
        fprintf(fid, '%% %s for %s, polynomial degree %d (generated by write_tables.m)\n', ...
            qname{iq}, R.problem, R.degs(id));
        fprintf(fid, '\\begin{tabular}{ll%s}\n\\toprule\n', repmat('c', 1, nM));
        fprintf(fid, '$h$ & $N_{int}$');
        fprintf(fid, ' & %s', R.methods{:});
        fprintf(fid, ' \\\\\n\\midrule\n');
        for im = 1:numel(R.mlist)
            fprintf(fid, '%.3g & %d', R.h(id,im), R.Nint(id,im));
            for iM = 1:nM
                fprintf(fid, ' & %s', fmt(D(id,im,iM)));
            end
            fprintf(fid, ' \\\\\n');
        end
        if ~strcmp(qs{iq}, 'sigma')
            fprintf(fid, '\\midrule\nconv. & order');
            for iM = 1:nM
                a = conv_order(R.h(id,:), D(id,:,iM));
                if isnan(a), fprintf(fid, ' & --'); else, fprintf(fid, ' & %.1f', a); end
            end
            fprintf(fid, ' \\\\\n');
        end
        fprintf(fid, '\\bottomrule\n\\end{tabular}\n');
        fclose(fid);
    end
end
end

function a = conv_order(h, e)
% Slope of the least-squares line fitted to (ln h_m, ln e_m), levels with finite error.
ok = isfinite(e) & isfinite(h) & e > 0;
if nnz(ok) < 2, a = NaN; return, end
c = polyfit(log(h(ok)), log(e(ok)), 1);  a = c(1);
end

function s = fmt(v)
% Number in the style of the paper's tables (e.g. 1.2e-05); NaN -> --
if isnan(v), s = '--'; else, s = sprintf('%.1e', v); end
end
